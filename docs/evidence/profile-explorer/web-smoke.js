// Runs in a NEW isolated browser context. Existing browser/app storage is untouched.
async (page) => {
  const context=await page.context().browser().newContext({viewport:{width:412,height:915}});
  const test=await context.newPage();
  const check=(value,message)=>{if(!value)throw new Error(message);};
  const key='world-maps:hot-cold:progress:v1';
  const fixture={schemaVersion:3,explored:['FRA','ITA'],difficulty:'normal',practiceMode:'random',voiceEnabled:false,sessions:[],learning:{'europe-countries':{POL:{correct:10,incorrect:2,firstTry:4,recent:[true,true,true],lastPracticed:101,lastRound:100,lastGuesses:['POL']}}}};
  await test.addInitScript(({key,fixture})=>{if(!localStorage.getItem(key)){localStorage.setItem(key,JSON.stringify(fixture));localStorage.setItem('world-maps:language:v1','en');}}, {key,fixture});
  const shot=async name=>{await test.waitForTimeout(350);await test.screenshot({path:`docs/evidence/profile-explorer/web-${name}.png`,animations:'disabled'});};
  const state=()=>test.evaluate(key=>JSON.parse(localStorage.getItem(key)),key);
  try {
    await test.goto('http://localhost:8081');
    await test.getByRole('tab',{name:/Profile/}).click();
    await test.getByText('Level 2 · Rookie',{exact:true}).waitFor();
    check(await test.getByText('190 XP',{exact:true}).isVisible(),'Old learning was not credited');
    await shot('profile');
    await test.getByRole('button',{name:'Your explorer',exact:true}).click();
    await test.getByRole('radio',{name:'Ocean',exact:true}).click();
    await shot('explorers');
    await test.getByRole('button',{name:'Close',exact:true}).click();
    await test.getByRole('dialog').waitFor({state:'hidden'});
    await test.reload();
    await test.getByRole('tab',{name:/Profile/}).click();
    await test.getByRole('button',{name:'Your explorer',exact:true}).click();
    check(await test.getByRole('radio',{name:'Ocean',exact:true}).getAttribute('aria-checked')==='true','Avatar was not restored');
    await test.getByRole('button',{name:'Close',exact:true}).click();
    await test.getByRole('dialog').waitFor({state:'hidden'});
    const migrated=await state();
    check(migrated.schemaVersion===4 && migrated.learning['europe-countries'].POL.correct===10 && migrated.explored.length===2,'Migration changed saved learning');
    check(migrated.practiceMode==='random' && migrated.voiceEnabled===false,'Migration changed preferences');
    await test.getByRole('button',{name:/^Europe\. 2\/47/}).click();
    await test.getByRole('textbox',{name:'Search country or capital',exact:true}).fill('Germany');
    await test.getByRole('button',{name:/Germany/}).click();
    await test.getByRole('tab',{name:/Profile/}).click();
    await test.getByText('Level 3 · Scout',{exact:true}).waitFor();
    check(await test.getByText('200 XP',{exact:true}).isVisible(),'Discovery did not unlock level/cap');
    const levelBox=await test.getByText('Level 3 · Scout',{exact:true}).boundingBox();
    check(levelBox && levelBox.y >= 0 && levelBox.y+levelBox.height < 915,'Newly earned level remained offscreen');
    await shot('unlocked');
    await test.getByRole('button',{name:'Your explorer',exact:true}).click();
    await shot('outfits');
    await test.getByRole('button',{name:'Close',exact:true}).click();
    await test.getByRole('dialog').waitFor({state:'hidden'});
    await test.getByRole('tab',{name:/Library/}).click();
    await test.getByRole('button',{name:/Back to collection/}).click();
    await test.getByRole('button',{name:/Germany/}).click();
    await test.getByRole('tab',{name:/Profile/}).click();
    check(await test.getByText('200 XP',{exact:true}).isVisible(),'Repeated country opening farmed XP');
    await test.getByRole('button',{name:/^Asia\./}).click();
    await test.getByRole('tab',{name:/Profile/}).click();
    check(await test.getByText('200 XP',{exact:true}).isVisible(),'Map switch reset player XP');
    await test.getByRole('button',{name:'All achievements',exact:true}).click();
    await test.getByRole('dialog').getByText('Globetrotter',{exact:true}).waitFor();
    await shot('achievements');
    await test.getByRole('button',{name:'Close',exact:true}).click();
    await test.getByRole('dialog').waitFor({state:'hidden'});
    await test.setViewportSize({width:320,height:568});
    await test.getByRole('button',{name:'How to earn XP',exact:true}).click();
    await test.getByRole('dialog').getByText('First-try bonus',{exact:true}).waitFor();
    await shot('xp-small');
    await test.getByRole('button',{name:'Close',exact:true}).click();
    await test.getByRole('dialog').waitFor({state:'hidden'});
    await test.getByRole('button',{name:'Your explorer',exact:true}).click();
    await shot('avatar-small');
    await test.getByRole('button',{name:'Close',exact:true}).click();
    await test.getByRole('dialog').waitFor({state:'hidden'});
    await test.emulateMedia({colorScheme:'dark'});
    await test.setViewportSize({width:412,height:915});
    await shot('dark');
    await test.evaluate(key=>localStorage.setItem(key,JSON.stringify({schemaVersion:99})),key);
    await test.reload();
    await test.getByRole('tab',{name:/Profile/}).click();
    await test.getByRole('alert').getByText('Saved progress could not be read. Retry before playing.',{exact:true}).waitFor();
    check(await test.getByRole('button',{name:'Your explorer',exact:true}).count()===0,'Read error exposed fictional progression');
    check((await state()).schemaVersion===99,'Future progress was overwritten');
    return 'PASS: read-error protection, v3 migration/backfill, avatar persistence, real discovery level/outfit unlock, repeat protection, cross-map XP, achievements, small controls and dark mode';
  } finally {await context.close();}
}
