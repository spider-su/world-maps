// Isolated context: no existing app/browser data is touched; external requests blocked.
async page => {
  const context = await page.context().browser().newContext({ viewport: { width: 390, height: 844 } });
  const test = await context.newPage();
  const errors = [];
  test.on('pageerror', error => errors.push(error.message));
  await test.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
  const key = 'world-maps:hot-cold:progress:v1';
  await test.addInitScript(key => {
    if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify({ schemaVersion: 4, explorer: 'ocean', explored: ['POL'], sessions: [], learning: {}, difficulty: 'normal', voiceEnabled: false, practiceMode: 'adaptive' }));
  }, key);
  const globe = () => test.getByTestId('globe-surface');
  const path = () => test.getByTestId('globe-land').getAttribute('d');
  const open = () => test.getByRole('button', { name: 'Explore the globe', exact: true }).click();
  const back = () => test.getByRole('button', { name: 'Back to Home', exact: true }).click();
  const reset = () => test.getByRole('button', { name: 'Centre globe on selected region', exact: true }).click();
  const changed = before => test.waitForFunction(before => document.querySelector('[data-testid="globe-land"]').getAttribute('d') !== before, before);
  const check = (value, detail) => { if (!value) throw new Error(detail); };
  const shot = name => test.screenshot({ path: `docs/evidence/globe/web-${name}.png` });
  try {
    await test.goto('http://127.0.0.1:8105');
    await open();
    await test.getByRole('tab', { name: /Home/ }).waitFor({ state: 'hidden' });
    const stored = await test.evaluate(key => localStorage.getItem(key), key);
    const initial = await path();
    await shot('globe');
    await globe().hover();
    await test.mouse.wheel(0, 100);
    await changed(initial);
    await shot('wheel');
    await reset();
    check(await path() === initial, 'Centre did not restore selected region');
    await globe().evaluate(node => node.dispatchEvent(new WheelEvent('wheel', { deltaY: 2, deltaMode: 1, bubbles: true, cancelable: true })));
    await changed(initial);
    await reset();
    const box = await globe().boundingBox();
    await test.mouse.move(box.x+box.width/2, box.y+box.height/2);
    await test.mouse.down();
    await test.mouse.move(box.x+box.width+15, box.y+box.height/2+25, { steps: 15 });
    await test.mouse.up();
    await changed(initial);
    await shot('drag');
    await reset();
    await globe().focus();
    await globe().press('ArrowRight');
    await changed(initial);
    await globe().press('ArrowUp');
    await test.waitForFunction(() => document.querySelector('[data-testid="globe-surface"]').getAttribute('aria-description').includes('66°'));
    await globe().press('Home');
    check(await path() === initial, 'Home key did not reset');
    await test.getByRole('button', { name: 'Rotate globe west', exact: true }).click();
    await changed(initial);
    await reset();
    await globe().dispatchEvent('pointercancel', { pointerId: 1, pointerType: 'mouse' });
    await back();
    await test.getByRole('tab', { name: /Home/ }).waitFor();
    await test.getByRole('button', { name: /^Name It\. Identify/ }).click();
    await back();
    await test.getByRole('button', { name: 'Maps: Europe', exact: true }).click();
    await test.getByRole('button', { name: /^Asia\b/ }).click();
    await test.waitForTimeout(400);
    await open();
    check(await path() !== initial, 'Globe did not focus Asia');
    const asia = await path();
    await globe().focus();
    await globe().press('ArrowLeft');
    await changed(asia);
    await reset();
    check(await path() === asia, 'Centre used previous region');
    await back();
    await test.reload();
    await open();
    check(await path() === asia, 'Region focus did not restore');
    check(await test.evaluate(key => localStorage.getItem(key), key) === stored, 'Globe changed progress');
    await back();
    await test.setViewportSize({ width: 320, height: 568 });
    await test.evaluate(() => localStorage.setItem('world-maps:language:v1', 'pl'));
    await test.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' });
    await test.reload();
    await test.getByRole('button', { name: 'Odkrywaj globus', exact: true }).click();
    await test.getByRole('group', { name: 'Interaktywny globus', exact: true }).waitFor();
    await shot('compact-pl');
    await test.getByRole('button', { name: 'Wróć do strony głównej', exact: true }).click();
    await test.evaluate(() => localStorage.setItem('world-maps:language:v1', 'ru'));
    await test.reload();
    await test.getByRole('button', { name: 'Исследовать глобус', exact: true }).click();
    await test.getByRole('group', { name: 'Интерактивный глобус', exact: true }).waitFor();
    await shot('compact-ru');
    check(errors.length === 0, errors.join('; '));
    return { pass: true, pageErrors: errors, checks: ['separate full-screen view and restored tabs/Back', 'pixel/line wheel', 'pointer drag/cancel', 'keyboard rotation/tilt/reset', 'direction buttons', 'normal quiz navigation', 'selected-region focus and relaunch', 'progress unchanged', 'PL/RU compact dark/reduced-motion', 'external requests blocked'] };
  } finally { await context.close(); }
}
