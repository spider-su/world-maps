import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.WORLD_MAPS_PLAYWRIGHT_MODULE || 'playwright');
const browser=await chromium.launch({headless:true});
const errors=[];const results=[];
const check=(value,message)=>{if(!value)throw Error(message);};
try{
 const context=await browser.newContext({viewport:{width:390,height:844}}),page=await context.newPage();
 page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>Object.defineProperty(navigator,'share',{value:async data=>{window.__share=data;}}));
 await page.goto('http://127.0.0.1:8115');
 await page.getByRole('button',{name:'My QR code',exact:true}).waitFor();
 await page.getByRole('button',{name:'My QR code',exact:true}).click();
 await page.getByLabel('Creating invitation…',{exact:true}).last().waitFor();
 await page.getByRole('button',{name:'Share invitation',exact:true}).waitFor();
 check(await page.locator('svg path').count()>0,'No QR rendered');
 check(await page.evaluate(()=>window.__calls.create)===1,'Duplicate invitation request');
 await page.screenshot({path:'docs/evidence/profile-sharing/web-my-qr.png'});
 await page.getByRole('button',{name:'Share invitation',exact:true}).click();
 check((await page.evaluate(()=>window.__share.text)).includes('https://world-map-1.web.app/friend?invite='),'Share invitation has no link');
 await page.getByRole('button',{name:'Close',exact:true}).click();await page.waitForTimeout(400);
 await page.getByRole('button',{name:'Scan QR code',exact:true}).click();
 await page.getByRole('button',{name:'Fixture decoded QR',exact:true}).click();
 await page.getByRole('heading',{name:'Friend invitation',exact:true}).waitFor();
 check(await page.evaluate(()=>window.__calls.accept)===0,'Scanning accepted without approval');
 await page.getByRole('button',{name:'Add friend',exact:true}).click();
 await page.getByLabel('Adding friend…',{exact:true}).waitFor();
 await page.getByText('Friend added',{exact:true}).waitFor();
 await page.getByText('Globetrotter',{exact:true}).waitFor();
 check(await page.evaluate(()=>window.__calls.accept)===1,'Duplicate acceptance');
 await page.getByRole('button',{name:'Share World Maps',exact:true}).click();
 check((await page.evaluate(()=>window.__share.text)).includes('https://world-map-1.web.app'),'Share app has no download URL');
 await page.screenshot({path:'docs/evidence/profile-sharing/web-friends.png'});
 results.push('delayed backend: QR, spinner, share URLs, explicit acceptance and friend list');await context.close();
 const appContext=await browser.newContext({viewport:{width:390,height:844}}),app=await appContext.newPage();
 app.on('pageerror',e=>errors.push(e.message));
 await appContext.route('**/*',r=>r.request().url().startsWith('http://127.0.0.1:8114')?r.continue():r.abort());
 await app.goto('http://127.0.0.1:8114');await app.getByText('Profile',{exact:true}).click();
 await app.getByRole('button',{name:'Share World Maps',exact:true}).scrollIntoViewIfNeeded();
 await app.getByLabel('Nickname',{exact:true}).fill('Atlas');await app.getByRole('switch',{name:'Share my progress with friends',exact:true}).click();
 await app.getByRole('button',{name:'Continue with Google',exact:true}).waitFor();
 check(!await app.getByLabel('Password',{exact:true}).count(),'Email form not collapsed');
 await app.screenshot({path:'docs/evidence/profile-sharing/web-profile.png'});
 await app.getByRole('button',{name:'Use an invitation link',exact:true}).click();
 await app.getByLabel('Paste your friend’s invitation link',{exact:true}).fill('https://world-map-1.web.app/friend?invite='+'a'.repeat(48));
 await app.getByRole('button',{name:'Continue',exact:true}).click();await app.getByRole('heading',{name:'Friend invitation',exact:true}).waitFor();
 check(await app.getByRole('button',{name:'Add friend',exact:true}).isDisabled(),'Acceptance enabled without sign-in');
 await app.screenshot({path:'docs/evidence/profile-sharing/web-approval-signed-out.png'});
 results.push('production export: consent, compact sign-in, valid link requires sign-in');await appContext.close();
 check(errors.length===0,errors.join('; '));console.log(JSON.stringify({results,errors}));
}finally{await browser.close();}
